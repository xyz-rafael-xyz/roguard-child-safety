def generate():
    result=[]
    for row in previous('train'):
        found=[]
        for label,phrases in TRAIN.items():
            for index,phrase in enumerate(phrases):
                if any(phrase.casefold() in t['text'].casefold() for t in row['turns']):
                    found.append((label,index,phrase))
        if len(found)!=1:raise ValueError('Ambiguous authored content family')
        label,index,phrase=found[0];replacement=CONTENT[label][index]
        turns=[dict(t,text=t['text'].replace(phrase,replacement).replace(phrase.lower(),replacement.lower()))
               for t in row['turns']]
        result.append(dict(row,case_id='bare95-'+str(len(result)),turns=turns,source='bare_distress_repair_v9'))
    return result
