def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    plan_path = args.output / 'drafting-plan.json'
    plan = json.loads(plan_path.read_text())
    assert plan['target_families'] == len(FRAMES) == 32
    rows, metadata = [], []
    for category, number, form, distinction, good_reason, bad_reason, ro, uk in FRAMES:
        family = f'diversity69:{category}:{number}'
        metadata.append(dict(family=family, form=form, intended_distinction=distinction,
                             appropriate_rationale=good_reason, problematic_rationale=bad_reason))
        for language, pair in [('ro', ro), ('uk', uk)]:
            for polarity, draft in enumerate(pair):
                rows.append(dict(case_id=f'{family}:{language}:{polarity}', family=family,
                                 language=language, partition='train', context='', draft=draft,
                                 gold='appropriate' if polarity == 0 else category,
                                 form=form, label_rationale=good_reason if polarity == 0 else bad_reason,
                                 provenance='assistant-authored-TRAIN-only-diversity-pilot',
                                 independently_annotated=False))
    assert len(rows) == plan['target_core_drafts'] == 128
    assert len({r['case_id'] for r in rows}) == len(rows)
    assert Counter(x[0] for x in FRAMES) == dict.fromkeys(['boundary', 'privacy', 'pressure', 'unsupported'], 8)
    encoded = ''.join(json.dumps(r, ensure_ascii=False, sort_keys=True) + '\n' for r in rows)
    report = dict(complete=True, author='assistant', families=len(metadata), core_drafts=len(rows),
                  plan_sha256=hashlib.sha256(plan_path.read_bytes()).hexdigest(),
                  source_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
                  train_draft_sha256=hashlib.sha256(encoded.encode()).hexdigest(),
                  forms_by_family=dict(sorted(Counter(r['form'] for r in metadata).items())),
                  groups=dict(sorted(Counter(f"{r['language']}:{r['gold']}" for r in rows).items())),
                  wrappers=0, context='empty; intended self-contained reply judgments',
                  training_ready=False, used_for_training=False, scaled=False,
                  human_validation=False, independent_semantic_validation=False,
                  semantic_independence_established=False, judge_run_launched=False,
                  reserved_test_opened=False, stable_release_ready=False)
    outputs = {'train-draft.jsonl': encoded,
               'intended-distinctions.json': json.dumps(metadata, ensure_ascii=False, indent=2) + '\n',
               'draft-report.json': json.dumps(report, ensure_ascii=False, indent=2) + '\n'}
    assert all(not (args.output / name).exists() for name in outputs), 'Refuse overwrite'
    for name, data in outputs.items():
        with (args.output / name).open('x') as stream:
            stream.write(data)
    print(json.dumps(report, indent=2))


if __name__ == '__main__':
    main()
