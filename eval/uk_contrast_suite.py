def main() -> None:
    path = ROOT / "data" / "synthetic" / f"{NAME}.jsonl"
    manifest = path.with_suffix(".manifest.json")
    if path.exists() or manifest.exists():
        raise FileExistsError("Ukrainian probe already exists")
    rows = build_rows()
    path.write_text("".join(json.dumps(row, ensure_ascii=False, sort_keys=True) + "\n" for row in rows), encoding="utf-8")
    manifest.write_text(json.dumps({
        "name": NAME, "rows": 48, "pairs": 24, "training_eligible": False,
        "taxonomy_status": "draft_unreviewed", "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
        "note": "Ukrainian symbolic descriptors only; no child utterances or response texts."
    }, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(manifest)


if __name__ == "__main__":
    main()
